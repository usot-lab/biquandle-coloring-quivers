@dataclass
class ParsedCode:
    label: str
    pCode: list
    signs: list
    comp_lengths: list
    
def parse_labeled_code(label, raw_code):
    left, right = raw_code.strip().split('/')
    signs = right.strip().split()

    inside = left.strip()[1:-1]   # remove [ ]
    raw_components = [c.strip() for c in inside.split(',')]

    pCode = []
    comp_lengths = []

    for comp in raw_components:
        if comp == "":
            comp_lengths.append(0)
            continue

        tokens = comp.split()
        entries = []

        for token in tokens:
            if token.endswith('^'):
                token = token[:-1]
            entries.append(int(token))

        pCode.extend(entries)
        comp_lengths.append(len(entries))

    return ParsedCode(label=label, pCode=pCode, signs=signs, comp_lengths=comp_lengths)
    
